/**
 * Invoice PDF Generator
 * Generates a clean, selectable-text PDF invoice using jsPDF and jspdf-autotable.
 * Runs entirely in the browser — no server upload.
 */

import jsPDF from "jspdf";
import "jspdf-autotable";
import type { InvoiceData, InvoiceTotals } from "@/lib/invoice";
import {
  CURRENCIES,
  formatCurrency,
  formatCurrencyFromMinor,
} from "@/lib/invoice";

/**
 * Generate a PDF invoice and return the jsPDF instance.
 * Caller is responsible for triggering download.
 */
export function generateInvoicePdf(
  invoice: InvoiceData,
  totals: InvoiceTotals,
  paperSize: "a4" | "letter" = "a4"
): jsPDF {
  const doc = new jsPDF({
    orientation: "portrait",
    unit: "mm",
    format: paperSize,
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = 20; // mm from left/right
  const contentWidth = pageWidth - margin * 2;
  let y = margin; // Current vertical position

  const currency = invoice.currency;
  const meta = CURRENCIES[currency];
  const colors: [number, number, number] = [28, 25, 23]; // stone-900
  const subColor: [number, number, number] = [120, 113, 108]; // stone-500
  const accentColor: [number, number, number] = [68, 104, 79]; // sage green

  // ========================================================================
  // Invoice Header
  // ========================================================================

  // Brand watermark (subtle)
  doc.setFontSize(8);
  doc.setTextColor(200);
  doc.setFont("helvetica", "normal");
  doc.text("Generated by FreelanceCalc.app", margin, y);
  y += 8;

  // Logo if provided
  if (invoice.freelancer.logoDataUrl) {
    try {
      doc.addImage(
        invoice.freelancer.logoDataUrl,
        "PNG",
        margin,
        y,
        30,
        15
      );
      y += 20;
    } catch {
      // Invalid image, skip
    }
  }

  // "INVOICE" heading
  doc.setFontSize(24);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(...colors);
  doc.text("INVOICE", margin, y);
  y += 10;

  // Invoice number and dates (right-aligned)
  doc.setFontSize(9);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(...subColor);
  const rightX = pageWidth - margin;

  doc.text("Invoice #", rightX - 50, y);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(...colors);
  doc.text(invoice.invoiceNumber, rightX, y);
  y += 5;

  doc.setFont("helvetica", "normal");
  doc.setTextColor(...subColor);
  doc.text("Issue Date", rightX - 50, y);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(...colors);
  doc.text(formatDate(invoice.issueDate), rightX, y);
  y += 5;

  if (invoice.dueDate) {
    doc.setFont("helvetica", "normal");
    doc.setTextColor(...subColor);
    doc.text("Due Date", rightX - 50, y);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(...colors);
    doc.text(formatDate(invoice.dueDate), rightX, y);
    y += 5;
  }
  y += 5;

  // ========================================================================
  // From / To section
  // ========================================================================

  const fromX = margin;
  const toX = margin + contentWidth / 2;

  // FROM
  doc.setFontSize(7);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(...subColor);
  doc.text("FROM", fromX, y);
  doc.text("BILL TO", toX, y);
  y += 5;

  // From details
  doc.setFontSize(10);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(...colors);
  doc.text(invoice.freelancer.name, fromX, y);
  y += 5;

  doc.setFont("helvetica", "normal");
  doc.setTextColor(80);
  doc.setFontSize(9);
  if (invoice.freelancer.email) {
    doc.text(invoice.freelancer.email, fromX, y);
    y += 4;
  }
  const fromAddress = [invoice.freelancer.address, invoice.freelancer.phone].filter(Boolean);
  fromAddress.forEach((line) => {
    doc.text(line, fromX, y);
    y += 4;
  });
  if (invoice.freelancer.taxId) {
    y += 2;
    doc.setFontSize(8);
    doc.text(`Tax ID: ${invoice.freelancer.taxId}`, fromX, y);
  }

  // Reset y for To section
  y = Math.max(y, margin + 40); // Reset to top of To section

  // To details
  y = margin + 30; // Start with the "BILL TO" label y + 5
  // Recalculate: the BILL TO label is at y = margin + 35 approximately
  const billToY = margin + 35;
  doc.setFontSize(10);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(...colors);
  doc.text(invoice.client.name, toX, billToY + 5);
  let clientY = billToY + 10;

  doc.setFont("helvetica", "normal");
  doc.setTextColor(80);
  doc.setFontSize(9);
  if (invoice.client.email) {
    doc.text(invoice.client.email, toX, clientY);
    clientY += 4;
  }
  const clientAddress = [invoice.client.address].filter(Boolean);
  clientAddress.forEach((line) => {
    doc.text(line, toX, clientY);
    clientY += 4;
  });
  if (invoice.client.taxId) {
    clientY += 2;
    doc.setFontSize(8);
    doc.text(`Tax ID: ${invoice.client.taxId}`, toX, clientY);
  }

  // ========================================================================
  // Line Items Table
  // ========================================================================

  // Move below the from/to section
  const maxSectionY = Math.max(billToY + 30, clientY + 5);
  y = Math.max(maxSectionY, margin + 50);
  y += 5;

  let colWidths = [70, 20, 25, 25];
  let tableTotalWidth = colWidths.reduce((a, b) => a + b, 0);

  // Scale columns to fit content width if too wide
  if (tableTotalWidth > contentWidth) {
    const scale = contentWidth / tableTotalWidth;
    colWidths = colWidths.map((w) => w * scale);
    tableTotalWidth = contentWidth;
  }

  // Column start X (left-aligned)
  const tableStartX = margin;

  const lineItemsTable: string[][] = invoice.lineItems.map((item, idx) => {
    const amount = item.quantity * item.rate;
    return [
      item.description || `Item ${idx + 1}`,
      `${item.quantity} ${item.rate > 1000 ? "" : ""}`,
      formatCurrency(item.rate, currency),
      formatCurrency(amount, currency),
    ];
  });

  (doc as any).autoTable({
    startY: y,
    margin: { left: tableStartX },
    head: [["Description", "Qty", "Rate", "Amount"]],
    body: lineItemsTable,
    columnStyles: {
      0: { cellWidth: colWidths[0], fontStyle: "bold" },
      1: { cellWidth: colWidths[1], halign: "center" },
      2: { cellWidth: colWidths[2], halign: "right" },
      3: { cellWidth: colWidths[3], halign: "right" },
    },
    headStyles: {
      fillColor: colors,
      textColor: [255, 255, 255],
      fontSize: 8,
      fontStyle: "bold",
    },
    bodyStyles: {
      fontSize: 9,
      textColor: colors,
    },
    alternateRowStyles: {
      fillColor: [245, 243, 241], // stone-100
    },
    theme: "striped",
    tableWidth: tableTotalWidth,
    showHead: "everyPage",
    rowPageBreak: "avoid",
  });

  // ========================================================================
  // Totals Section
  // ========================================================================

  y = (doc as any).lastAutoTable.finalY + 5;

  const totalsX = pageWidth - margin - 60; // Right side
  const totalsLabelX = totalsX;
  const totalsValueX = pageWidth - margin;

  doc.setFontSize(9);

  // Subtotal
  doc.setFont("helvetica", "normal");
  doc.setTextColor(...subColor);
  doc.text("Subtotal", totalsLabelX, y);
  doc.setTextColor(...colors);
  doc.text(formatCurrencyFromMinor(totals.subtotal, currency), totalsValueX, y, { align: "right" });
  y += 6;

  // Discount (if applicable)
  if (invoice.discountPercent > 0) {
    doc.setFont("helvetica", "normal");
    doc.setTextColor(...subColor);
    doc.text(`Discount (${invoice.discountPercent}%)`, totalsLabelX, y);
    doc.setTextColor(220, 80, 80);
    doc.text(`- ${formatCurrencyFromMinor(totals.discountAmount, currency)}`, totalsValueX, y, { align: "right" });
    y += 6;
  }

  // Tax (if applicable)
  if (invoice.taxPercent > 0) {
    doc.setFont("helvetica", "normal");
    doc.setTextColor(...subColor);
    doc.text(`Tax (${invoice.taxPercent}%)`, totalsLabelX, y);
    doc.setTextColor(...colors);
    doc.text(`+ ${formatCurrencyFromMinor(totals.taxAmount, currency)}`, totalsValueX, y, { align: "right" });
    y += 6;
  }

  // Total
  y += 2;
  doc.setDrawColor(...accentColor);
  doc.setLineWidth(0.5);
  doc.line(totalsLabelX, y, totalsValueX + 5, y);
  y += 6;

  doc.setFontSize(12);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(...colors);
  doc.text("Total", totalsLabelX, y);
  doc.text(formatCurrencyFromMinor(totals.total, currency), totalsValueX, y, { align: "right" });
  y += 8;

  // Amount Paid / Balance Due (if applicable)
  if (invoice.amountPaid > 0) {
    doc.setFontSize(9);
    doc.setFont("helvetica", "normal");
    doc.setTextColor(...subColor);
    doc.text("Amount Paid", totalsLabelX, y);
    doc.setTextColor(...colors);
    doc.text(`- ${formatCurrencyFromMinor(totals.amountPaid, currency)}`, totalsValueX, y, { align: "right" });
    y += 6;

    // Balance Due
    doc.setFont("helvetica", "bold");
    doc.setTextColor(...accentColor);
    doc.text("Balance Due", totalsLabelX, y);
    doc.text(formatCurrencyFromMinor(totals.balanceDue, currency), totalsValueX, y, { align: "right" });
    y += 8;
  }

  // ========================================================================
  // Notes / Payment Instructions
  // ========================================================================

  // Check if we need a new page
  const pageHeight = doc.internal.pageSize.getHeight();
  if (y > pageHeight - 40) {
    doc.addPage();
    y = margin;
  }

  y += 3;

  // Payment Instructions
  if (invoice.paymentInstructions) {
    doc.setFontSize(7);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(...subColor);
    doc.text("PAYMENT INSTRUCTIONS", margin, y);
    y += 5;

    doc.setFont("helvetica", "normal");
    doc.setTextColor(80);
    doc.setFontSize(8);
    const paymentLines = doc.splitTextToSize(invoice.paymentInstructions, contentWidth);
    paymentLines.forEach((line: string) => {
      if (y > pageHeight - margin) {
        doc.addPage();
        y = margin;
      }
      doc.text(line, margin, y);
      y += 4;
    });
    y += 5;
  }

  // Notes
  if (invoice.notes) {
    doc.setFontSize(7);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(...subColor);
    doc.text("NOTES", margin, y);
    y += 5;

    doc.setFont("helvetica", "normal");
    doc.setTextColor(80);
    doc.setFontSize(8);
    const noteLines = doc.splitTextToSize(invoice.notes, contentWidth);
    noteLines.forEach((line: string) => {
      if (y > pageHeight - margin) {
        doc.addPage();
        y = margin;
      }
      doc.text(line, margin, y);
      y += 4;
    });
  }

  // ========================================================================
  // Footer
  // ========================================================================

  const footerY = pageHeight - 10;
  doc.setFontSize(7);
  doc.setTextColor(180);
  doc.setFont("helvetica", "italic");

  const pageCount = doc.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.text(
      `Invoice ${invoice.invoiceNumber} — Page ${i} of ${pageCount}`,
      pageWidth / 2,
      footerY,
      { align: "center" }
    );
  }

  return doc;
}

/**
 * Format ISO date string to readable format.
 */
function formatDate(dateStr: string): string {
  if (!dateStr) return "";
  try {
    const date = new Date(dateStr + "T00:00:00");
    return date.toLocaleDateString("en-US", {
      year: "numeric",
      month: "short",
      day: "numeric",
    });
  } catch {
    return dateStr;
  }
}